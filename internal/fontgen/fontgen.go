// Package fontgen parses, validates, and generates the PICO-8 glyph atlas.
package fontgen

import (
	"bufio"
	"bytes"
	"errors"
	"fmt"
	"image"
	"image/color"
	"image/png"
	"os"
	"strconv"
	"strings"
)

// Record is one P8SCII byte's 1-bit glyph data.
type Record struct {
	Byte  byte
	Width uint8
	Rows  [6]uint8
}

// Parse parses glyph data in the checked-in glyphs.txt format.
func Parse(data []byte) ([256]Record, error) {
	var records [256]Record
	var seen [256]bool

	scanner := bufio.NewScanner(bytes.NewReader(data))
	scanner.Buffer(make([]byte, 0, 64*1024), 64*1024)
	lineNumber := 0
	for scanner.Scan() {
		lineNumber++
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}

		fields := strings.Fields(line)
		if len(fields) != 8 {
			return records, fmt.Errorf("line %d: got %d fields, want 8 (byte width row0..row5)", lineNumber, len(fields))
		}
		value, err := parseHex(fields[0], 8)
		if err != nil {
			return records, fmt.Errorf("line %d: byte: %w", lineNumber, err)
		}
		b := byte(value)
		if seen[b] {
			return records, fmt.Errorf("line %d: duplicate byte %#02x", lineNumber, b)
		}
		seen[b] = true

		width, err := parseHex(fields[1], 8)
		if err != nil {
			return records, fmt.Errorf("line %d: width: %w", lineNumber, err)
		}
		record := Record{Byte: b, Width: uint8(width)}
		for i := range record.Rows {
			row, err := parseHex(fields[2+i], 8)
			if err != nil {
				return records, fmt.Errorf("line %d: row %d: %w", lineNumber, i, err)
			}
			record.Rows[i] = uint8(row)
		}
		if err := validateRecord(record); err != nil {
			return records, fmt.Errorf("line %d: byte %#02x: %w", lineNumber, b, err)
		}
		records[b] = record
	}
	if err := scanner.Err(); err != nil {
		return records, fmt.Errorf("read glyph data: %w", err)
	}
	for b, ok := range seen {
		if !ok {
			return records, fmt.Errorf("missing byte %#02x", b)
		}
	}
	return records, nil
}

// ParseFile reads and parses a glyph data file.
func ParseFile(path string) ([256]Record, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return [256]Record{}, fmt.Errorf("read %s: %w", path, err)
	}
	return Parse(data)
}

func parseHex(text string, bits int) (uint64, error) {
	value, err := strconv.ParseUint(text, 16, bits)
	if err != nil {
		return 0, fmt.Errorf("%q is not a %d-bit hexadecimal value", text, bits)
	}
	return value, nil
}

func validateRecord(record Record) error {
	switch record.Width {
	case 4:
		if record.Byte >= 0x80 {
			return errors.New("width 4 is invalid for bytes 0x80-0xff")
		}
		for i, row := range record.Rows {
			if row&0xf0 != 0 {
				return fmt.Errorf("row %d has ink outside the 4-pixel width: %#02x", i, row)
			}
		}
	case 8:
		if record.Byte < 0x80 {
			return errors.New("width 8 is invalid for bytes 0x00-0x7f")
		}
	default:
		return fmt.Errorf("width = %d, want 4 or 8", record.Width)
	}
	if record.Byte < 0x10 {
		if record.Width != 4 {
			return errors.New("control byte must use width 4")
		}
		for i, row := range record.Rows {
			if row != 0 {
				return fmt.Errorf("control byte row %d must be blank, got %#02x", i, row)
			}
		}
	}
	return nil
}

// GenerateGo returns the deterministic contents of atlas_gen.go.
func GenerateGo(records [256]Record) []byte {
	var out bytes.Buffer
	out.WriteString("// Code generated by tools/fontgen from glyphs.txt; DO NOT EDIT.\n\n")
	out.WriteString("package font\n\n")
	out.WriteString("// glyphs is the checked-in PICO-8 0.2.7 font atlas, indexed by P8SCII")
	out.WriteString(" byte.\n")
	out.WriteString("var glyphs = [256]Glyph{\n")
	for _, record := range records {
		fmt.Fprintf(&out, "\t{Width: %d, Rows: [6]uint8{0x%02x, 0x%02x, 0x%02x, 0x%02x, 0x%02x, 0x%02x}},\n",
			record.Width,
			record.Rows[0], record.Rows[1], record.Rows[2],
			record.Rows[3], record.Rows[4], record.Rows[5],
		)
	}
	out.WriteString("}\n")
	return out.Bytes()
}

// GeneratePNG returns a deterministic 16x16-tile atlas for inspection.
// Each tile is 8x8 pixels; the glyph occupies its top-left 4x6 or 8x6 area.
func GeneratePNG(records [256]Record) ([]byte, error) {
	const tiles = 16
	const tileSize = 8
	const side = tiles * tileSize

	palette := color.Palette{
		color.RGBA{A: 0xff},
		color.RGBA{R: 0xff, G: 0xff, B: 0xff, A: 0xff},
	}
	img := image.NewPaletted(image.Rect(0, 0, side, side), palette)
	for b, record := range records {
		x0 := (b % tiles) * tileSize
		y0 := (b / tiles) * tileSize
		for y := 0; y < 6; y++ {
			for x := 0; x < int(record.Width); x++ {
				if record.Rows[y]&(1<<x) != 0 {
					img.SetColorIndex(x0+x, y0+y, 1)
				}
			}
		}
	}

	var out bytes.Buffer
	encoder := png.Encoder{CompressionLevel: png.BestCompression}
	if err := encoder.Encode(&out, img); err != nil {
		return nil, fmt.Errorf("encode atlas PNG: %w", err)
	}
	return out.Bytes(), nil
}
